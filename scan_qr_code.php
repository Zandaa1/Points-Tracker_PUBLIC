    <script>
        let isScanning = true;
        let lastScanTime = 0;
        const SCAN_DELAY = 5000; // 5 seconds lockout

        function onScanSuccess(decodedText, decodedResult) {
            const currentTime = Date.now();
            if (currentTime - lastScanTime < SCAN_DELAY) {
                return; // Ignore scans within the lockout period
            }

            if (!isScanning) return;

            lastScanTime = currentTime;
            // Pause scanning visually (optional, but good UX)
            // html5QrcodeScanner.pause(); 

            // Send to backend
            fetch('api/scan_process.php', {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json',
                },
                body: JSON.stringify({ unique_text: decodedText })
            })
            .then(response => response.json())
            .then(data => {
                showModal(data.success, data.message, data.points_added);
                if (data.success && data.new_total !== undefined) {
                    document.getElementById('current-points-display').innerText = data.new_total;
                }
            })
            .catch(error => {
                console.error('Error:', error);
                showModal(false, "An error occurred. Please try again.");
            });
        }

        function onScanFailure(error) {
            // handle scan failure, usually better to ignore and keep scanning.
            // console.warn(`Code scan error = ${error}`);
        }

        let html5QrcodeScanner = new Html5QrcodeScanner(
            "reader",
            { fps: 10, qrbox: {width: 250, height: 250} },
            /* verbose= */ false);
        html5QrcodeScanner.render(onScanSuccess, onScanFailure);

        // Modal Logic
        const modal = document.getElementById('result-modal');
        const modalTitle = document.getElementById('modal-title');
        const modalMessage = document.getElementById('modal-message');
        const modalIcon = document.getElementById('modal-icon');

        function showModal(success, message, points) {
            modal.classList.remove('hidden');
            
            if (success) {
                modalTitle.innerText = 'Success!';
                modalMessage.innerText = message;
                modalIcon.innerHTML = `<svg class="h-10 w-10 text-white" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M5 13l4 4L19 7"></path></svg>`;
                modalIcon.className = "mx-auto flex items-center justify-center h-16 w-16 rounded-full bg-pwu-maroon mb-4";
            } else {
                modalTitle.innerText = 'Oops!';
                modalMessage.innerText = message;
                modalIcon.innerHTML = `<svg class="h-10 w-10 text-white" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M6 18L18 6M6 6l12 12"></path></svg>`;
                modalIcon.className = "mx-auto flex items-center justify-center h-16 w-16 rounded-full bg-pwu-maroon mb-4";
            }
        }

        function closeModal() {
            modal.classList.add('hidden');
            // Resume scanning if paused
            // html5QrcodeScanner.resume();
        }
